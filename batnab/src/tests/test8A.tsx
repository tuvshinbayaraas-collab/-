/** One of the five parabolas offered for "y = 3(x − 2)² − 1", drawn like the book's sketches (not to scale). */
const parabola = (h: number, k: number, up: boolean, yCut: string, xs: [number, number]) => {
  const f = (x: number) => (up ? 1 : -1) * (x - h) ** 2 + k;
  const cut = f(0);
  const lo = Math.min(k, cut, 0) - 1;
  const hi = Math.max(k, cut, 0) + 1;
  return (
    <Plot
      x={xs}
      y={[lo, hi]}
      scale={13}
      origin={false}
      curve={f}
      dashed={[
        [
          [0, k],
          [h, k],
        ],
        [
          [h, 0],
          [h, k],
        ],
      ]}
      // Over the axis where the vertex is below it (the curve leaves that side free there).
      xLabels={[[h, h < 0 ? `−${-h}` : `${h}`, k < 0 ? 'above' : undefined]]}
      yLabels={[
        [k, k < 0 ? `−${-k}` : `${k}`],
        [cut, yCut],
      ]}
    />
  );
};

